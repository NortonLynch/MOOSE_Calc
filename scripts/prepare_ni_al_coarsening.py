cg, cp = 0.124644, 0.237162
G0, Vm, x0, Dref = 1000., 7e-6, 1e-9, 1e-18
f0 = G0 / Vm
t0 = x0*x0 / Dref
sigma, width = 0.020, 4e-9
sigma_star, width_star = sigma/(f0*x0), width/x0
barrier = 6*sigma_star*np.log(9)/width_star
kappa = 3*sigma_star*width_star/np.log(9)
curvature = {}
fit_report = {}
fig, axes = plt.subplots(1, 2, figsize=(9, 3.6), layout='constrained')
for ax, phase, ceq in zip(axes, ['gamma', 'gamma_prime'], [cg, cp]):
    df = pd.read_csv(DATA / f'{phase}_1000K.csv')
    local = df.loc[np.abs(df.x_Al-ceq) <= 0.00101]
    assert len(local) >= 5
    # Fit the slope of diffusion potential; retain the CALPHAD tie-line exactly.
    A = float(np.polyfit(local.x_Al-ceq, local.dGm_reduced_dx_J_mol, 1)[0])
    assert A > 0
    curvature[phase] = A
    view = df.loc[np.abs(df.x_Al-ceq) <= 0.00401]
    ax.plot(100*view.x_Al, view.Gm_reduced_J_mol, 'o-', label='NIDEMO export')
    ax.plot(100*view.x_Al, 0.5*A*(view.x_Al-ceq)**2, '--', label='Local quadratic model')
    ax.set(title=phase, xlabel='Al (at.%)', ylabel='Reduced G (J/mol)')
    ax.legend(fontsize=8)
    fit_report[phase] = {'curvature_J_mol': A, 'fit_half_range_x_Al': 0.00101, 'fit_points': len(local)}
fig.savefig(OUT / 'free_energy_approximation.png', dpi=160)
plt.close(fig)
Ag, Ap = curvature['gamma']/G0, curvature['gamma_prime']/G0
mobility = 1/Ag
L = 10.
size, n = 96., 96
particles = [(24.,24.,9.2), (72.,24.,9.7), (24.,72.,10.3), (72.,72.,10.8)]
ell = width_star/(2*np.log(9))
x, y = np.meshgrid(np.linspace(0,size,n+1), np.linspace(0,size,n+1))
eta = np.ones_like(x)
terms = []
for a,b,r in particles:
    eta *= 1 - 0.5*(1-np.tanh((np.hypot(x-a,y-b)-r)/(2*ell)))
    terms.append(f'(1-0.5*(1-tanh((sqrt((x-{a})^2+(y-{b})^2)-{r})/{2*ell:.16g})))')
eta = 1-eta
h = eta**3*(6*eta**2-15*eta+10)
q = (1-h)/Ag+h/Ap
weights = np.ones_like(x)
weights[[0,-1],:] *= .5
weights[:,[0,-1]] *= .5
mean = lambda v: float(np.sum(v*weights)/n**2)
mu0 = (0.14 - mean(cg+h*(cp-cg)))/mean(q)
cinit = cg+h*(cp-cg)+mu0*q
assert abs(mean(cinit)-.14) < 1e-14
eta_expr = '1-'+'*'.join(terms)
h_expr = 'eta^3*(6*eta^2-15*eta+10)'
f_expr = f'h:={h_expr};q:=(1-h)/{Ag:.16g}+h/{Ap:.16g};0.5*(c-{cg}-h*{cp-cg:.16g})^2/q+{barrier:.16g}*eta^2*(1-eta)^2'
c_expr = f'eta0:={eta_expr};h:=eta0^3*(6*eta0^2-15*eta0+10);{cg}+h*{cp-cg:.16g}+({mu0:.16g})*((1-h)/{Ag:.16g}+h/{Ap:.16g})'
